/**
 * Подобрать ответ по сообщению пользователя.
 * Возвращает undefined, если ни один шаблон не совпал (для свободных ответов).
 */
export function pickReply(userMessage: string): string | undefined {
  const msg = userMessage.toLowerCase();
  for (const tpl of REPLIES) {
    if (tpl.match.some((m) => msg.includes(m.toLowerCase()))) return tpl.reply;
  }
  return undefined;
}
